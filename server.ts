import express from 'express';
import { createServer as createViteServer } from 'vite';
import path from 'path';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const app = express();
const PORT = 3000;

app.use(express.json({ limit: '10mb' }));

// Audio cache for instantaneous replay and high performance at the booth
const audioCache = new Map<string, string>();

let aiClient: GoogleGenAI | null = null;
function getAIClient(): GoogleGenAI {
  if (!aiClient) {
    aiClient = new GoogleGenAI({
      apiKey: process.env.GEMINI_API_KEY,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    });
  }
  return aiClient;
}

// API endpoint for natural, lifelike AI voice synthesis
app.post('/api/tts', async (req, res) => {
  try {
    const { 
      text, 
      voice = 'Kore', 
      style = 'A real, articulate young adult woman having a relaxed, normal conversation with another person. Casual, friendly, and confident tone. Smooth and natural delivery with realistic pacing, subtle pauses, and organic changes in intonation. Natural contractions, conversational phrasing, subtle emphasis on key words, and rising intonation on questions. Zero robotic or monotone delivery, no overly formal announcer tone, no exaggerated enthusiasm, and not reading from a script.' 
    } = req.body;

    if (!text || typeof text !== 'string') {
      return res.status(400).json({ error: 'Text parameter is required' });
    }

    const cleanText = text.trim();
    if (!cleanText) {
      return res.status(400).json({ error: 'Text cannot be empty' });
    }

    // Check cache
    const cacheKey = `${voice}:${cleanText}`;
    if (audioCache.has(cacheKey)) {
      return res.json({
        audio: audioCache.get(cacheKey),
        mimeType: 'audio/wav',
        cached: true,
      });
    }

    if (!process.env.GEMINI_API_KEY) {
      return res.status(503).json({ 
        error: 'GEMINI_API_KEY is not configured on the server. Falling back to local synthesizer.' 
      });
    }

    const ai = getAIClient();

    // Call Gemini 3.8 Flash Lite TTS model
    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-lite-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: cleanText,
              speechMetadata: {
                style,
              },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName: voice },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
    if (!base64Audio) {
      return res.status(500).json({ error: 'No audio generated by model' });
    }

    // Cache to memory (keep last 300 entries)
    if (audioCache.size > 300) {
      const oldestKey = audioCache.keys().next().value;
      if (oldestKey) audioCache.delete(oldestKey);
    }
    audioCache.set(cacheKey, base64Audio);

    return res.json({
      audio: base64Audio,
      mimeType: 'audio/wav',
      cached: false,
    });
  } catch (error: any) {
    console.error('Gemini TTS error:', error?.message || error);
    return res.status(500).json({
      error: error?.message || 'TTS generation encountered an error',
    });
  }
});

async function startServer() {
  if (process.env.NODE_ENV === 'production') {
    const distPath = path.resolve(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(distPath, 'index.html'));
    });
  } else {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`THE FACT SPIN server running on http://0.0.0.0:${PORT}`);
  });
}

startServer();
